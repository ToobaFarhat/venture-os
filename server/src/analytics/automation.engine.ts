import mongoose from 'mongoose';
import { Automation, Task, Notification } from '../models';
import { AuditService } from '../services/audit.service';

export interface AutomationTriggerEvent {
  workspaceId: string;
  triggerType: 'lead_score_threshold' | 'negative_feedback' | 'revenue_drop' | 'task_overdue';
  data: any;
}

export class AutomationEngine {
  public static async evaluateAndTrigger(event: AutomationTriggerEvent): Promise<void> {
    try {
      const wsId = new mongoose.Types.ObjectId(event.workspaceId);
      const activeAutomations = await Automation.find({
        workspaceId: wsId,
        triggerType: event.triggerType,
        isEnabled: true,
      });

      for (const rule of activeAutomations) {
        let conditionMet = false;

        if (rule.triggerType === 'lead_score_threshold') {
          const score = event.data?.score ?? 0;
          const threshold = rule.triggerConfig?.threshold ?? 80;
          conditionMet = score >= threshold;
        } else if (rule.triggerType === 'negative_feedback') {
          const sentiment = event.data?.sentiment;
          const urgency = event.data?.urgency;
          conditionMet = sentiment === 'negative' || urgency === 'high' || urgency === 'critical';
        } else if (rule.triggerType === 'revenue_drop') {
          const dropPct = event.data?.dropPercentage ?? 0;
          const threshold = rule.triggerConfig?.threshold ?? 15;
          conditionMet = dropPct >= threshold;
        } else if (rule.triggerType === 'task_overdue') {
          conditionMet = true;
        }

        if (conditionMet) {
          await this.executeAction(rule, event);
          rule.executionCount = (rule.executionCount || 0) + 1;
          rule.lastTriggeredAt = new Date();
          await rule.save();
        }
      }
    } catch (err) {
      console.error('[AutomationEngine] Error evaluating automations:', err);
    }
  }

  private static async executeAction(rule: any, event: AutomationTriggerEvent): Promise<void> {
    const wsId = new mongoose.Types.ObjectId(event.workspaceId);

    if (rule.actionType === 'create_task') {
      const title = rule.actionConfig?.taskTitleTemplate
        ? rule.actionConfig.taskTitleTemplate.replace('{{name}}', event.data?.name || 'Lead/Account')
        : `Automated follow-up: ${event.data?.name || 'Trigger Event'}`;

      const task = await Task.create({
        workspaceId: wsId,
        title,
        description: `Task automatically generated by automation rule "${rule.name}" in response to ${event.triggerType}.`,
        priority: rule.actionConfig?.taskPriority || 'high',
        status: 'todo',
        originType: 'automation',
        originId: rule._id,
        dueDate: new Date(Date.now() + 2 * 24 * 60 * 60 * 1000), // 48 hours
      });

      await AuditService.record({
        workspaceId: wsId,
        action: 'automation.task_created',
        resource: 'Task',
        resourceId: task._id.toString(),
        details: { ruleId: rule._id, ruleName: rule.name, triggerType: event.triggerType },
      });
    }

    if (rule.actionType === 'send_notification' || rule.actionType === 'create_task') {
      await Notification.create({
        workspaceId: wsId,
        title: rule.actionConfig?.notificationTitle || `Automation Alert: ${rule.name}`,
        message: rule.actionConfig?.notificationMessage || `Rule "${rule.name}" triggered on ${event.triggerType}.`,
        type: 'automation',
      });
    }
  }
}
